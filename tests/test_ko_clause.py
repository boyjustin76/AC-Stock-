def test_쉼표_뒤는_가장_좋은_자리다():
    """`가격이` 가 보조용언 어간 `가` 로 잘못 읽혀 쉼표 뒤가 막혔던 적이 있다.
    이정찬 수정본 99개 경계 가운데 쉼표·마침표 뒤를 안 끊은 자리가 없었다 — 상을 준다."""
    어절 = "볼린저 밴드 하단에 가격이 닿아 매수했음에도 불구하고, 가격이 밴드를 타고 하락했습니다".split()
    i = 어절.index("가격이", 4)                      # 쉼표 바로 뒤의 `가격이`
    쉼표 = ko_clause.경계벌점(어절, i)
    assert 쉼표 is not None and 쉼표 < 0
    다른값 = [ko_clause.경계벌점(어절, j) for j in range(1, len(어절)) if j != i]
    assert 쉼표 < min(v for v in 다른값 if v is not None)


def test_길이는_기준이_아니라_한계다():
    조각 = ko_clause.조각내기("따라서 밴드와의 단순 접촉은 진입 신호가 아니라, 변동성이 확대될 수 있다는 "
                              "객관적인 경고 신호로 받아들여야 합니다")
    길이 = [len(ko_clause.맨(c)) for c in 조각]
    assert max(길이) <= ko_clause.최대기본
    assert min(길이) >= 4                             # 토막 큐가 없다
    assert sum(길이) == len(ko_clause.맨("".join(조각)))


def test_태그는_말뭉치에서_읽는다():
    """글자만 보면 못 가르는 짝 — 모델이 있으면 제대로 가른다."""
    if not ko_clause.모델()["어절"]:
        return                                        # 모델 파일이 없는 환경이면 건너뛴다
    assert ko_clause.끝태그("설정은") == "JX"          # 명사 + 보조사
    assert ko_clause.끝태그("사용하는") == "ETM"       # 용언 + 관형형 전성어미
    assert ko_clause.끝태그("객관적인") == "ETM"
    assert ko_clause.끝태그("경고") not in ("EC", "EC_대등")   # `고` 로 끝나도 명사다
