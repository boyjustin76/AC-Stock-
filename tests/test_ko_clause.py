def test_쉼표_뒤는_1급이고_아무것도_막지_못한다():
    """이정찬 수정본 99개 경계 가운데 쉼표·마침표 뒤를 안 끊은 자리가 없었다 — 1급이다.
    두 번 깨졌다: ① `가격이` 가 보조용언 어간 `가` 로 읽혀 막혔다
    ② 복합명사 금지가 먼저 걸려 `기간 20, | 표준편차` 가 막혔다. 그래서 구두점을 맨 먼저 본다."""
    어절 = "볼린저 밴드 하단에 가격이 닿아 매수했음에도 불구하고, 가격이 밴드를 타고 하락했습니다".split()
    i = 어절.index("가격이", 4)                      # 쉼표 바로 뒤의 `가격이`
    assert ko_clause.경계벌점(어절, i) == 1
    어절2 = "가장 많이 쓰는 설정은 기간 20, 표준편차 2의 기본 밴드입니다".split()
    assert ko_clause.경계벌점(어절2, 어절2.index("표준편차")) == 1   # 복합명사 금지보다 앞선다


def test_글자_수는_기준이_아니다():
    """이정찬 2026-10-02: "글자 수를 신경쓰지마. 넌 그냥 말 되는거에만 신경써."
    그래서 1급(구두점)·2급(절 끝)에서만 끊는다. 3급(조사·관형절)은 조각이 아주 길 때만 쓴다."""
    문장 = ("따라서 밴드와의 단순 접촉은 진입 신호가 아니라, 변동성이 확대될 수 있다는 "
            "객관적인 경고 신호로 받아들여야 합니다")
    조각 = ko_clause.조각내기(문장)
    assert "".join(ko_clause.맨(c) for c in 조각) == ko_clause.맨(문장)   # 글자를 잃지 않는다
    어절 = 문장.split()
    for 앞조각 in 조각[:-1]:
        i = 어절.index(앞조각.split()[-1]) + 1
        값 = ko_clause.경계벌점(어절, i)
        assert 값 is not None and 값 <= 2, "끊은 자리가 1·2급이 아니다: %s" % 앞조각


def test_아주_긴_문장만_3급_자리를_쓴다():
    # 조사·관형절 자리(3급)만 있고 아주 길지 않으면 한 조각으로 둔다.
    # 길이로 끊으면 `확정하는 | 선이` 처럼 관형형과 꾸밈받는 말이 갈린다 (이정찬 대조 2026-10-02).
    짧은문장 = "상하단 밴드는 절대 매매를 확정하는 선이 아닙니다"
    assert len(ko_clause.조각내기(짧은문장)) == 1
    긴문장 = " ".join(["아주 긴 명사구와 조사가 이어지는 문장을"] * 3) + " 만들어 봅니다"
    assert len(ko_clause.조각내기(긴문장)) >= 2        # 아주길다를 넘으면 쪼갠다


def test_태그는_말뭉치에서_읽는다():
    """글자만 보면 못 가르는 짝 — 모델이 있으면 제대로 가른다."""
    if not ko_clause.모델()["어절"]:
        return                                        # 모델 파일이 없는 환경이면 건너뛴다
    assert ko_clause.끝태그("설정은") == "JX"          # 명사 + 보조사
    assert ko_clause.끝태그("사용하는") == "ETM"       # 용언 + 관형형 전성어미
    assert ko_clause.끝태그("객관적인") == "ETM"
    assert ko_clause.끝태그("경고") not in ("EC", "EC_대등")   # `고` 로 끝나도 명사다
