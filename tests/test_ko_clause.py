def test_관형절_끝은_끊을_수_있지만_구두점보다_비싸다():
    """이정찬 손수정본(2026-10-01, 99줄)이 관형절 끝에서 자주 끊는다 —
    `접촉했다는 | 단일 사실`, `회귀하는 | 20일 중심선`, `하나가 아닌 | 두 개를`.
    처음엔 아예 막아 뒀는데 그게 틀렸다. 절 경계니 허용하되 구두점보다는 비싸게 둔다."""
    어절 = "밴드에 가격이 접촉했다는 단일 사실 하나만 보고".split()
    값 = ko_clause.경계벌점(어절, 어절.index("단일"))
    assert 값 is not None and 값 > 0
    어절2 = "진입 신호가 아니라, 변동성이 확대될 수 있다는".split()
    assert ko_clause.경계벌점(어절2, 어절2.index("변동성이")) < 값   # 쉼표 뒤가 더 좋은 자리다


def test_따옴표_안을_가르지_않는다():
    조각, 경계 = 가름("오늘은 볼린저 밴드를 하나가 아닌 두 개를 겹쳐 사용하는 "
                      "‘더블 볼린저 밴드’ 매매법을 통해 휩소를 걸러냅니다")
    assert "볼린저|밴드’" not in 경계
    for c in 조각:                                   # 여는 짝과 닫는 짝이 한 조각 안에 같이 있어야 한다
        assert c.count("‘") == c.count("’")


