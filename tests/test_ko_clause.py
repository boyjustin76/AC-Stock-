import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools", "cutedit"))
import ko_clause


def 가름(문장):
    """조각 사이의 경계를 '앞말|뒷말' 꼴로 돌려준다."""
    조각 = ko_clause.조각내기(문장)
    경계 = []
    for a, b in zip(조각, 조각[1:]):
        경계.append("%s|%s" % (a.split()[-1], b.split()[0]))
    return 조각, 경계


def test_보조용언을_본용언에서_떼지_않는다():
    _, 경계 = 가름("현재 가격이 평균적인 변동 범위에서 얼마나 멀어졌는지를 수치로 알려 주는 하나의 기준선일 뿐입니다")
    assert "알려|주는" not in 경계
    _, 경계 = 가름("이때 가격은 밴드 안에 머물지 않고 밴드 밖으로 이탈하여 한 방향으로 움직입니다")
    assert "머물지|않고" not in 경계
    _, 경계 = 가름("변동성이 확대될 수 있다는 객관적인 경고 신호로 받아들여야 합니다")
    assert "받아들여야|합니다" not in 경계
    _, 경계 = 가름("거래 수수료 페이백까지 무료로 제공하고 있으니 많은 관심 부탁드립니다")
    assert "제공하고|있으니" not in 경계


