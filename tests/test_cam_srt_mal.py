"""말한 대로 쓰는 자막(cam_srt_말) 시험.

시험하는 것은 **짐작이 들어갈 수 있는 두 군데**다 —
  · 낱말을 문장으로 끊는 자리 (문장부호 · 벌어진 사이)
  · 조각(큐)마다의 시각을 낱말에서 되짚는 자리 — 여기서 어긋나면 자막이 통째로 밀린다
컷→시퀀스 시각 변환도 함께 본다 (컷에 걸친 낱말을 컷 안쪽으로 자르는가).
"""
import importlib.util
import os

_길 = os.path.join(os.path.dirname(__file__), '..', 'tools', 'cutedit', 'cam_srt_말.py')
_스펙 = importlib.util.spec_from_file_location('cam_srt_mal', _길)
말 = importlib.util.module_from_spec(_스펙)
_스펙.loader.exec_module(말)


def test_문장은_문장부호_뒤에서_끊는다():
    ws = [('안녕', 0.0, 0.5), ('하세요.', 0.5, 1.0), ('오늘은', 1.1, 1.5), ('시작합니다.', 1.5, 2.0)]
    assert [[w[0] for w in d] for d in 말.문장나누기(ws, 0.6)] == \
        [['안녕', '하세요.'], ['오늘은', '시작합니다.']]


def test_문장은_벌어진_사이에서도_끊는다():
    """컷으로 덜어 낸 자리는 낱말 사이가 벌어진다 — 문장부호가 없어도 끊어야 한다."""
    ws = [('추세를', 0.0, 0.5), ('봅니다', 0.5, 1.0), ('그리고', 3.0, 3.4), ('색을', 3.4, 3.8)]
    assert len(말.문장나누기(ws, 0.6)) == 2
    assert len(말.문장나누기(ws, 3.0)) == 1          # 사이를 넓게 잡으면 한 덩어리


def test_컷_경계에서는_반드시_끊는다():
    """컷을 이어 붙이면 시퀀스에서 사이가 0초라, 컷 번호로만 가를 수 있다 (10-08)."""
    ws = [('가르는', 0.0, 0.5, 3), ('색이', 0.5, 1.0, 4), ('그대로면', 1.0, 1.5, 4)]
    덩 = 말.문장나누기(ws, 0.6)
    assert [[w[0] for w in d] for d in 덩] == [['가르는'], ['색이', '그대로면']]


def test_조각시각은_낱말에서_되짚는다():
    덩어리 = [('색이', 10.0, 10.4), ('바뀌면', 10.4, 10.9), ('전환으로', 11.2, 11.7),
              ('봅니다.', 11.7, 12.3)]
    때 = 말.조각시각(덩어리, ['색이 바뀌면', '전환으로 봅니다.'])
    assert 때[0] == (10.0, 10.9)
    assert 때[1] == (11.2, 12.3)


def test_조각시각은_낱말_가운데서_갈라도_그_낱말을_쓴다():
    """조각 경계가 낱말 가운데 떨어져도 시각은 그 낱말의 것이어야 한다 (띄어쓰기가 다를 때)."""
    덩어리 = [('들어갑니다', 5.0, 6.0), ('색만', 6.0, 6.5), ('보세요', 6.5, 7.0)]
    때 = 말.조각시각(덩어리, ['들어갑니다', '색만 보세요'])
    assert 때[0] == (5.0, 6.0)
    assert 때[1] == (6.0, 7.0)


def test_컷에_걸친_낱말은_컷_안쪽으로_자른다():
    받 = [{'words': [{'w': ' 앞', 's': 9.0, 'e': 11.0},      # 컷 머리에 걸침
                     {'w': ' 가운데', 's': 12.0, 'e': 13.0},
                     {'w': ' 밖', 's': 30.0, 'e': 31.0}]}]   # 컷 밖 — 빠진다
    표 = [(10.0, 20.0, 0.0)]                                 # 원본 10~20초 → 시퀀스 0초부터
    out = 말.남은낱말(받, 표)
    assert [w[0] for w in out] == ['앞', '가운데']
    assert out[0][1] == 0.0 and abs(out[0][2] - 1.0) < 1e-9  # 9.0 은 컷 머리(10.0)로 당겨진다
    assert abs(out[1][1] - 2.0) < 1e-9


def test_두_컷이면_시퀀스_시각이_이어_붙는다():
    받 = [{'words': [{'w': ' 하나', 's': 10.5, 'e': 11.0},
                     {'w': ' 둘', 's': 50.2, 'e': 50.8}]}]
    컷 = {'cuts': [{'src': 'x', 'in': 10.0, 'out': 12.0},
                   {'src': 'x', 'in': 50.0, 'out': 52.0},
                   {'src': 'x', 'in': 99.0, 'out': 99.5, 'track': 2}]}   # V2 는 안 쓴다
    표 = 말.표만들기(컷, {'x': 0.0}, 29.97)
    assert len(표) == 2
    assert abs(표[1][2] - 2.0) < 0.02                        # 첫 컷 길이만큼 밀려 시작한다
    out = 말.남은낱말(받, 표)
    assert abs(out[1][1] - 2.2) < 0.02                       # 50.2 → 2.0 + 0.2
