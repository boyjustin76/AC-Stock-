def test_무음_빼기():
    assert subtract([(0.0, 10.0)], [(3.0, 4.0)]) == [(0.0, 3.0), (4.0, 10.0)]
    assert subtract([(0.0, 10.0)], [(0.0, 2.0), (9.0, 12.0)]) == [(2.0, 9.0)]
    assert subtract([(5.0, 6.0)], [(0.0, 10.0)]) == []          # 통째로 무음이면 남는 게 없다


def test_대본에_없는_꼬리말을_뗀다():
    ws = [(0.0, 0.5, '따라서', 1.0), (0.5, 1.0, '밴드와의', 1.0), (1.0, 1.5, '접촉은', 1.0),
          (1.6, 1.8, '아', 0.1), (1.8, 2.1, '다시', 0.5), (2.1, 2.6, '하겠습니다', 0.3)]
    out = trim_to_script(ws, '따라서 밴드와의 접촉은')
    assert [w[2] for w in out] == ['따라서', '밴드와의', '접촉은']


def test_대본과_다르게_말한_낱말은_안_뗀다():
    """`순서는 셋이에요` 를 `순서는 셋입니다` 로 말했다 — 떼면 말한 게 컷에서 사라진다 (10-08)."""
    ws = [(0.0, 0.9, '순서는', 1.0), (0.9, 2.6, '셋입니다.', 1.0)]
    assert [w[2] for w in trim_to_script(ws, '순서는 셋이에요.')] == ['순서는', '셋입니다.']


def test_앞머리_헛말도_뗀다():
    ws = [(0.0, 0.4, '오늘은', 0.9), (0.4, 0.8, '볼린저', 0.9),
          (1.5, 2.0, '오늘은', 0.9), (2.0, 2.6, '볼린저', 0.9), (2.6, 3.2, '밴드를', 0.9)]
    out = trim_to_script(ws, '오늘은 볼린저 밴드를')
    assert out[-1][2] == '밴드를'
    assert len(out) <= 4          # 되풀이한 앞머리가 빠졌다


def test_확신도는_겹친_길이로_가중한다():
    ws = [(0.0, 1.0, '가', 1.0), (1.0, 2.0, '나', 0.0)]
    assert abs(conf(ws, 0.0, 2.0) - 0.5) < 1e-6
    assert abs(conf(ws, 0.0, 1.0) - 1.0) < 1e-6


def test_재촬영_이어붙이기가_문장_첫머리를_안_날린다():
    """앞 테이크가 문장 첫머리에서 시작하지 않으면 이어 붙이지 않는다 (10-01 사고)."""
    a = {'i': 1, 's': 10.0, 'e': 20.0, 'text': '가나다 라마바 사아자'}
    words = [(13.0, 14.0, '라마바', 1.0), (14.0, 15.0, '사아자', 1.0),
             (17.0, 18.0, '라마바', 1.0), (18.0, 19.0, '사아자', 1.0)]
    segs = [{'s': 13.0, 'e': 15.0, 'text': '라마바 사아자'},
            {'s': 17.0, 'e': 19.0, 'text': '라마바 사아자'}]
    #  앞 테이크(13초)가 문장 시작(10초)보다 3초 늦다 → 이어 붙이지 않는다
    assert retake_spans(a, segs, words) is None


def test_옆_문장_자리는_재촬영이_아니다():
    """이웃한 두 문장이 글자로 거의 같아도 이어 붙이면 안 된다 (10-08 사고).

    `청록색으로 … 매수로 들어갑니다` 와 `반대로 자홍색으로 … 매도로 들어가겠습니다` 는
    0.45 넘게 닮았다. 뒷문장을 앞문장의 재촬영으로 보면 앞문장 뒷머리 5초가 통째로 날아간다.
    """
    a = {'i': 54, 's': 347.7, 'e': 352.8, 'text': '청록색으로 바뀐 캔들의 종가에서 매수로 들어갑니다'}
    segs = [{'s': 347.7, 'e': 352.8, 'text': '청록색으로 바뀐 캔들이 종가에서 매수로 들어갑니다'},
            {'s': 353.2, 'e': 358.1, 'text': '반대로 자홍색으로 바뀐 캔들이 종가에서는 매도로 들어가겠습니다'}]
    words = [(347.7, 349.1, '청록색으로', 1.0), (349.1, 350.0, '바뀐', 1.0),
             (350.0, 350.9, '종가에서', 1.0), (350.9, 352.8, '들어갑니다', 1.0),
             (353.2, 354.3, '반대로', 1.0), (354.3, 356.3, '자홍색으로', 1.0),
             (356.3, 358.1, '들어가겠습니다', 1.0)]
    assert retake_spans(a, segs, words) is not None          # 옆 자리를 안 알려 주면 걸려든다
    assert retake_spans(a, segs, words, [(353.2, 358.1)]) is None   # 알려 주면 안 걸린다


def test_컷_경계에_걸친_한_낱말은_두_번_말한_게_아니다():
    """낱말 하나가 두 컷에 걸치면 글자는 같아 보여도 한 번 말한 것이다 (10-08 `입니다` 사고).

    떼어 내면 그 말이 통째로 사라진다 — 앞 컷은 `…선이 하나`, 뒤 컷은 `니다 보조지표를` 이 된다.
    """
    말 = (105.80, 106.86, '입니다', 1.0)
    w1 = words_touch([말], 103.10, 106.36)          # 앞 컷에 걸친다
    w2 = words_touch([말], 106.68, 112.84)          # 뒤 컷에도 걸친다 — **같은 낱말이다**
    assert w1 and w2
    assert not 두번말했나(w1, w2)


def test_토막째_다시_말했으면_뒤엣것을_쓴다():
    """막혔다가 그 토막을 통째로 다시 말한 자리 — 앞엣것을 버린다 (마02 OUTRO 10-08)."""
    ws = [(10.0, 11.0, '정해둔', 1.0), (11.0, 12.0, '자리에서', 1.0), (12.0, 13.0, '나온', 1.0),
          (14.0, 15.0, '정해둔', 1.0), (15.0, 16.0, '자리에서', 1.0), (16.0, 17.0, '나온다', 1.0)]
    남, 구멍 = 되풀이빼기(ws, [])
    assert [w[0] for w in 남] == [14.0, 15.0, 16.0]
    assert 구멍 == [(10.0, 13.0)]          # 뗀 자리는 **구멍으로** 넘겨야 컷에서도 빠진다


def test_되풀이는_토막_꼬리에만_붙기도_한다():
    """앞 토막이 멀쩡한 앞부분을 달고 있으면 **꼬리만** 떼어 낸다 (마02 OUTRO)."""
    ws = [(1.0, 2.0, '선을올리고설정을맞춘다', 1.0),
          (2.0, 3.0, '직전저점과고점에손절을걸고', 1.0),
          (5.0, 6.0, '직전저점과고점에손절을걸고', 1.0)]
    남, 구멍 = 되풀이빼기(ws, [])
    assert [w[2] for w in 남] == ['선을올리고설정을맞춘다', '직전저점과고점에손절을걸고']
    assert 구멍 == [(2.0, 3.0)]
    assert 남[-1][0] == 5.0                # 남은 것은 **뒤엣것**이다


def test_낱말이_붙어_있어도_침묵이_있으면_토막이_갈린다():
    """받아쓰기는 낱말 끝을 다음 낱말 머리까지 늘여 적는다 — 벌어짐만 보면 못 가른다."""
    ws = [(10.0, 11.0, '나온', 1.0), (11.0, 12.0, '직전', 1.0)]
    assert len(토막내기(ws, [])) == 1                    # 붙어 있으니 한 토막
    assert len(토막내기(ws, [(10.8, 11.4)])) == 2        # 사이에 침묵이 걸쳐 있으면 둘


def test_닮지_않은_토막은_둘_다_남는다():
    """이어지는 다른 말은 버리면 안 된다 — 닮음이 문턱을 넘을 때만 버린다."""
    ws = [(10.0, 11.0, '청록색으로바뀐캔들은매수', 1.0),
          (12.0, 13.0, '자홍색으로바뀐캔들은매도', 1.0)]
    남, 구멍 = 되풀이빼기(ws, [], 닮음=0.95)
    assert len(남) == 2 and 구멍 == []


def test_말_없는_꼬리는_컷에_안_남긴다():
    """정렬 구간이 문장 끝 뒤 침묵까지 품고 있어도 컷은 마지막 낱말에서 끝나야 한다 (10-08).

    무음 지도가 그 침묵을 놓치면 6초짜리 빈 컷이 선다 — `chunks` 가 끝을 낱말에 맞춘다.
    """
    al = [{'i': 1, 'sec': 'OUTRO', 's': 660.0, 'e': 680.0, 'text': '정해둔 자리에서 나온다'}]
    words = [(660.0, 661.0, '정해둔', 1.0), (661.0, 662.0, '자리에서', 1.0),
             (662.0, 663.0, '나온다', 1.0)]          # 663~680 은 말이 없다
    out = chunks(al, words, [], 0.30, 0.10, 0.20, 0.25)
    assert len(out) == 1
    assert abs(out[0]['end'] - 663.2) < 1e-6         # 마지막 낱말 끝 + 꼬리 0.2


def test_두_번_말한_것은_떼어_낸다():
    """같은 글자라도 낱말이 둘이면 두 번 말한 것이다 (마01 `변동성이` 0.2초 간격)."""
    a = (10.0, 10.6, '변동성이', 1.0)
    b = (10.8, 11.4, '변동성이', 1.0)
    assert 두번말했나([a], [b])
    assert not 두번말했나([a], [(11.0, 11.5, '확대될', 1.0)])


def test_이어_붙인_시각을_파일별로_되돌린다():
    """캠 파일이 둘이면 컷은 **그 파일 안의 시각**으로 나가야 한다 (마02 아웃트로 재촬영)."""
    파일들 = [{'파일': '마02_CAM 모음.mp4', '시작': 0.0, '길이': 803.333},
              {'파일': '마02_CAM_Outro.mp4', '시작': 803.333, '길이': 154.2}]
    자리 = 이어붙인자리(파일들)
    assert [z[2] for z in 자리] == ['마02_CAM ', '마02_CAM_']      # 키가 갈린다
    쪽 = 파일조각(자리, 810.0, 820.0)
    assert len(쪽) == 1 and 쪽[0][0] == '마02_CAM_'
    assert abs(쪽[0][1] - 6.667) < 0.01                            # 둘째 파일 안에서는 6.7초
    #  파일 경계를 걸친 구간은 둘로 갈린다 — 한 클립이 두 파일에 걸칠 수는 없다
    assert [z[0] for z in 파일조각(자리, 800.0, 810.0)] == ['마02_CAM ', '마02_CAM_']
    #  숨 쉴 틈이 경계를 살짝 넘어 생긴 부스러기(0.1초)는 버린다
    assert [z[0] for z in 파일조각(자리, 803.248, 810.0)] == ['마02_CAM_']


def test_무음은_파일마다_시각을_옮겨_모은다():
    파일들 = [{'파일': 'a.mp4', '시작': 0.0, '길이': 10.0},
              {'파일': 'b.mp4', '시작': 10.0, '길이': 10.0}]
    소리 = [{'파일': 'a.mp4', '무음': [[1.0, 2.0], [3.0, 3.1]]},
            {'파일': 'b.mp4', '무음': [[1.0, 2.0]]}]
    assert 무음모으기(소리, 파일들, 0.35) == [(1.0, 2.0), (11.0, 12.0)]   # 0.1초 숨은 남는다


