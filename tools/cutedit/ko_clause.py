"""한국어 자막 큐를 **구·절 단위**로 가른다. 글자 수가 아니라 형태소 태그가 기준이다.

왜 따로 만들었나 (2026-10-01, 마01 이정찬 지적 "자막이 기준이 없이 나뉘어져있어")
  `srt_rules.split_cue` 는 길이를 맞추는 쪽이라 말이 안 되는 자리에서 끊긴다. 실제로 나온 것:
    `… 수치로 알려` / `주는 하나의 기준선일 뿐입니다`   ← 본용언과 보조용언을 갈랐다
    `… 하나가 아닌 두` / `개를 겹쳐 사용하는`           ← 수관형사와 의존명사를 갈랐다
    `… 사용하는 '더블 볼린저` / `밴드' 매매법을 통해,`    ← 따옴표 안을 갈랐다
    `… 있다는 객관적인` / `경고 신호로 받아들여야 합니다` ← 관형형과 꾸밈받는 말을 갈랐다
    `… 추세를 형성하기` / `시작할 때는 문제가 달라집니다` ← 명사형과 서술어를 갈랐다
  `split_cue` 는 숏폼 14자 규칙을 사람 수정본(S015·S016)으로 맞춘 것이라 손대지 않는다.
  이 모듈은 **롱폼 낭독 자막** 전용이다.

판정은 짐작이 아니라 **모두의 말뭉치 형태 분석(MP)** 에서 뽑은 태그 모델로 한다.
  글자만 보면 `설정은`(명사+보조사 JX)과 `깊은`(용언+관형형 ETM)을 가를 수 없다. 말뭉치에는 답이 있다.
  모델은 `tools/cutedit/data/ko_tags.json.gz` (어절 33.6만개에서 뽑은 끝꼴·앞꼴 태그 · 0.4MB).
  만드는 법은 `ko_tags_build.py`. 모델이 없으면 글자꼴 규칙으로 물러난다(정확도만 떨어진다).

기준 — **글자 수는 기준이 아니다** (이정찬 2026-10-02: "글자 수를 신경쓰지마. 넌 그냥 말 되는거에만
신경써. 글자 수는 내가 해결할거니까. 애초에 가로 화면이라 딱히 제약도 없고")

  그래서 노리는 것이 바뀌었다. **적게 끊고, 끊은 자리는 전부 사람이 받아들일 자리여야 한다.**
  길이를 맞추려고 애매한 자리를 끊으면 `오르는 | 경우도`·`확정하는 | 선이` 처럼 말이 끊긴다
  (이정찬 손수정본과 맞대 24곳 가운데 7곳이 이것이었다, 2026-10-02 실측).

  ① **못 끊는 자리** — 관형격(JKG '의')·관형사(MM) 뒤 · 명사형(ETN) 뒤 · 의존명사(NNB)만으로 끝난 뒤 ·
     뒤가 보조용언(VX)·의존명사(NNB)·부사(MAG)·`아니다`(VCN)·`이다`(VCP) 일 때 · 따옴표·괄호 안 ·
     앞말 없이 못 서는 용언(`불구하고`·`비해`) 앞 · 복합명사 사이
  ② **끊는 자리는 등급으로 가른다**
     **1급** 마침표·쉼표 뒤 — 늘 끊는다
     **2급** 종결어미(EF)·연결어미(EC) 뒤 — 절이 끝난 자리다. 끊어도 좋다
     **3급** 조사(JX·JKB·JKS·JKO) 뒤 · 관형절(ETM) 뒤 — **조각이 너무 길 때만** 쓴다
  ③ 길이는 **마지막 수단**이다. `아주길다`(40자) 를 넘는 조각이 생길 때만 3급을 쓴다.
"""
import gzip
import io
import json
import os
import re

# 글자 수는 기준이 아니다 — 3급 경계를 쓸지 말지 가르는 **마지막 수단**으로만 쓴다
아주길다 = 40
최대기본, 최소기본, 이상기본 = 0, 0, 0      # 남겨 둠(옛 부름말 호환). 0 이면 길이를 안 본다
길어짐기준 = 0
_모델 = None


def 모델():
    global _모델
    if _모델 is None:
        길 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "ko_tags.json.gz")
        try:
            with gzip.open(길, "rt", encoding="utf-8") as f:
                _모델 = json.load(f)
        except Exception:
            _모델 = {"어절": {}, "끝꼴": {}, "앞꼴": {}, "보조용언": [], "의존명사": []}
        _모델.setdefault("어절", {})
    return _모델


# 길이를 셀 때 공백과 **가느다란 기호**(+ → ·)는 안 센다 — 화면에서 글자 폭을 거의 안 먹는다.
# 이걸 세면 `밴드 확장 + 강한 장대봉 동반 → 추세 추종 매매` 가 한계를 넘어 `추종 매매` 4자로 쪼개진다.
맨 = lambda s: re.sub(r"[\s+→·]", "", s)
_군더더기 = re.compile(r"""[\s'"‘’“”.,!?()\[\]/·…~\-+:;]""")
알만 = lambda s: _군더더기.sub("", s)

# 말뭉치에 없는 꼴을 만났을 때 쓰는 물러섬 규칙 (글자꼴만 본다)
_물러_끝 = [
    (re.compile(r"(습니다|입니다|니다|세요|십시오|어요|아요|예요|죠|까요|나요)$"), "EF"),
    (re.compile(r"(면서|지만|는데|니까|거나|더라도|도록|므로|다가|라면|다면|고자|려고|으며|으면|고|며|면)$"), "EC_대등"),
    (re.compile(r"(아서|어서|여서|아야|어야|여야|아|어|여|게|지|고서)$"), "EC_보조"),
    (re.compile(r"(기|음|ㅁ)$"), "ETN"),
    (re.compile(r"(적인|스러운|같은|다운|로운|하는|되는|있는|없는|했던|하던|되던|던|할|될)$"), "ETM"),
    (re.compile(r"의$"), "JKG"),
    (re.compile(r"(은|는|도|만|까지|부터|마다|조차|밖에|이나|라도)$"), "JX"),
    (re.compile(r"(에서|에게|한테|으로|로|와|과|에|보다|처럼|같이)$"), "JKB"),
    (re.compile(r"(을|를|이|가)$"), "JKO"),
]
_한음절관형 = {"두", "한", "세", "네", "다섯", "여섯", "몇", "여러", "각", "이", "그", "저",
               "매", "온", "전", "새", "첫", "옛", "약", "총", "뭐", "무슨", "어떤", "모든"}


def 끝태그(어절):
    """어절의 **끝 형태소 태그**. ① 말뭉치 어절 사전 ② 끝꼴(2글자 이상) ③ 글자꼴 규칙."""
    글 = 알만(어절)
    if not 글: return None
    낱 = 모델()["어절"].get(글)
    if 낱: return 낱[1]
    표 = 모델()["끝꼴"]
    for k in range(min(5, len(글)), 1, -1):              # 1글자 꼴은 안 쓴다 — 너무 모호하다
        값 = 표.get(글[-k:])
        if 값 and 값[1] >= 0.75 and 값[2] >= 3:
            return 값[0]
    # 글자꼴 물러섬. 어간이 한 글자만 남아도 쓴다 — `띠며`·`닿아` 같은 짧은 용언꼴이
    # 여기까지 와서, 막아 두면 절 경계(연결어미)를 놓친다.
    # `경고` 를 `고`(연결어미)로 읽던 사고는 **어절 사전(8.8만)이 막아 준다** — 사전에 NNG 로 있다.
    for 재, 태 in _물러_끝:
        m = 재.search(글)
        if m and len(글) > (m.end() - m.start()): return 태
    return None


def 첫태그(어절):
    글 = 알만(어절)
    if not 글: return None
    낱 = 모델()["어절"].get(글)
    if 낱: return 낱[0]
    표 = 모델()["앞꼴"]
    for k in range(min(4, len(글)), 1, -1):
        값 = 표.get(글[:k])
        if 값 and 값[1] >= 0.75 and 값[2] >= 3:
            return 값[0]
    return None


# 어간 뒤에 붙는 어미 꼴 — 보조용언을 알아볼 때 쓴다
_어미꼬리 = re.compile(r"^(는|은|ㄴ|던|을|ㄹ|지|고|서|면|며|니|나|자|게|기|음|도록|려고"
                       r"|았|었|겠|아|어|여|야|요|다|까|네|죠"
                       r"|습니다|ㅂ니다|니다|세요|십시오|어요|아요|는다|ㄴ다|는데|지만"
                       r"|으며|으면|으니|으나|으므로|으면서|으려고|으시|었으|겠으"
                       r"|아서|어서|여서|아야|어야|여야|기는|지는)+$")


# 줄어든 보조용언꼴 — 어간이 바뀌어서 어간+어미로는 못 맞춘다.
# `합니다` 는 `하` 로 시작하지 않고(합≠하), `됩니다` 도 `되` 로 시작하지 않는다.
# 이것 때문에 `받아들여야 | 합니다` 가 갈렸다 (2026-10-02 실측).
_줄어든보조 = {
    "합니다", "한다", "해", "해서", "해야", "했다", "했습니다", "하죠", "하자", "합시다",
    "됩니다", "된다", "돼", "돼서", "됐다", "됐습니다",
    "봅니다", "본다", "봐", "봐서", "봤다", "보죠",
    "줍니다", "준다", "줘", "줘서", "줬다", "주죠",
    "놓습니다", "놨다", "둡니다", "뒀다", "버립니다", "버렸다", "드립니다", "드렸다",
    "않습니다", "않는다", "않죠", "없습니다", "있습니다", "갑니다", "옵니다", "맙니다",
    "싶습니다", "싶다", "말아야", "마세요", "계십니다",
}


def _보조용언인가(어절):
    """`주는`·`않고`·`합니다`·`있다는` 처럼 앞말에 붙어 쓰이는 보조용언인가.

    어간만 보고 앞가지로 맞추면 안 된다 — 보조용언 목록에 `가` 가 있어서 **`가격이`** 를
    보조용언으로 읽었고, 그 바람에 쉼표 뒤(`불구하고, | 가격이`)를 못 끊었다 (2026-10-01 실측).
    어간 뒤가 **어미** 일 때만 보조용언으로 본다.
    """
    글 = 알만(어절)
    if 글 in _줄어든보조: return True
    if 첫태그(어절) == "VX": return True
    if 글 in 모델()["보조용언"]: return True
    for w in 모델()["보조용언"]:
        if 글.startswith(w) and len(글) > len(w) and _어미꼬리.match(글[len(w):]):
            return True
    return False


# 복수 `들` 을 빼먹어 `분들은` 이 의존명사로 안 잡혔다 (이정찬 수정본 대조 2026-10-02)
_조사꼬리 = re.compile(
    r"^(들)?(이|가|은|는|을|를|에|의|도|만|과|와|로|으로|에서|에게|부터|까지|보다|처럼|이나|나"
    r"|이다|이라|이며|이고|입니다|이면|이지만|이므로|라도|조차|마저|밖에|마다|뿐|씩|째)?$")


def _의존명사인가(어절):
    """의존명사(+조사) 꼴인가. `개를`·`것은`·`수`·`때는` ○ / `적용`·`개발`·`일정한` ×

    느슨하게 보면 안 된다 — `적` 이 의존명사라고 `적용` 을 의존명사로 읽어서
    `… 편차 4, 적용` / `가격은 …` 처럼 복합명사를 가르는 쪽으로 몰렸다 (2026-10-01 실측).
    """
    글 = 알만(어절)
    if 첫태그(어절) == "NNB" and _조사꼬리.match(글[1:] if len(글) > 1 else ""): return True
    for w in 모델()["의존명사"]:
        if 글 == w: return True
        if 글.startswith(w) and _조사꼬리.match(글[len(w):]) and 글[len(w):]: return True
    return False


# 앞의 체언 없이는 못 서는 용언들 — `~에도 불구하고`, `~에 비해`, `~을 통해`, `~에 대해`
의존용언 = {"불구하고", "불구하여", "비해", "비하여", "대해", "대하여", "대한", "위해", "위하여", "위한",
            "통해", "통하여", "통한", "관해", "관하여", "관한", "의해", "의하여", "의한",
            "따라", "따라서는", "달리", "있어", "있어서", "한하여", "제외하고", "비롯한", "비롯해", "대비", "기준으로", "한해"}


_보조적어미끝 = re.compile(r"(아|어|여|려|워|해|야|게|지|고|기)$")
# **절을 닫는** 연결어미 — 여기까지가 2급이다. `-게`·`-아/어/여` 는 들어가지 않는다
절닫는어미 = re.compile(r"(고|며|면|면서|지만|는데|은데|ㄴ데|니까|거나|더라도|도록|므로|다가"
                        r"|라면|다면|든지|고자|려고|으며|으면|으니|으므로|자|지라도)$")


def 경계벌점(어절들, i):
    """어절 i-1 과 i 사이에서 끊는 값. None 이면 끊을 수 없다."""
    앞, 뒤 = 어절들[i - 1], 어절들[i]
    앞맨 = 알만(앞)

    # 구두점 뒤는 **무엇보다 먼저** 본다 — 이정찬 수정본 99개 경계 가운데 쉼표·마침표 뒤를
    # 안 끊은 자리가 없었다. 뒤로 두면 복합명사 금지에 먹힌다 (`기간 20, | 표준편차` 가 막혔다).
    if re.search(r"[.?!…,;:]$", 앞.strip()):
        글앞 = " ".join(어절들[:i])
        막힘 = any(글앞.count(열) > 글앞.count(닫) for 열, 닫 in (("‘", "’"), ("“", "”"), ("(", ")")))
        # 문장 머리의 짧은 접속·순서말 뒤는 끊지 않는다 — `단,` `첫째,` `둘째,` `오늘 내용,`.
        # 떼어 놓으면 한 어절만 떠 있는 큐가 된다 (이정찬은 전부 붙여 두었다, 2026-10-02).
        if not 막힘 and i > 2: return 1

    # ① 따옴표·괄호 안
    글 = " ".join(어절들[:i])
    for 열, 닫 in (("‘", "’"), ("“", "”"), ("(", ")"), ("[", "]")):
        if 글.count(열) > 글.count(닫): return None
    for 짝 in ("'", '"'):
        if 글.count(짝) % 2: return None

    앞태, 뒤태 = 끝태그(앞), 끝태그(뒤)
    if 앞맨 in _한음절관형: return None                  # `두 | 개를`, `이 | 검정색`
    # 관형사 태그는 MM·MMD(지시)·MMA(성상)·MMN(수) 로 갈린다 — 앞가지로 한꺼번에 막는다
    if 앞태 and (앞태.startswith("MM") or 앞태 in ("JKG", "ETN", "NNB", "XPN", "MAJ")):
        return None
    if _의존명사인가(뒤): return None                    # `두 | 개를`, `확대될 | 수 있다는`, `원하시는 | 분들은`
    if 알만(뒤) in 의존용언: return None                 # `매수했음에도 | 불구하고`, `밴드에 | 비해`
    if _보조용언인가(뒤) and (앞태 in ("EC", "EC_보조", "ETN") or _보조적어미끝.search(앞맨)):
        return None                                      # `알려 | 주는`, `머물지 | 않고`, `받아들여야 | 합니다`
    뒤첫, 뒤맨 = 첫태그(뒤), 알만(뒤)
    # **부사 앞에서는 끊지 않는다** — 부사는 뒤의 용언과 한 덩어리다.
    # 이정찬은 거꾸로 **부사 뒤**에서 끊는다(`모두 | 밴드에`·`절대 | 매매를`·`함께 | 거래`).
    # 내가 `트레이더가 | 가장`·`돌파는 | 무조건`·`매매를 | 많이` 로 끊던 자리다 (2026-10-02 실측).
    if 뒤첫 in ("MAG", "MAJ"): return None
    # 접속조사 뒤는 끊지 않는다 — `강력한 캔들과 | 밴드 확장이` 처럼 병렬을 가른다.
    # 말뭉치는 `-와/과` 를 부사격(JKB)으로 태깅해서 태그만으로는 못 잡는다 — 글자꼴로 본다.
    if 앞태 == "JC" or re.search(r"[가-힣](와|과)$", 앞맨): return None
    # `아니다`(VCN)·`이다`(VCP) 는 앞의 보어와 한 덩어리다 — `하나가 | 아닌` 을 막는다
    if 뒤첫 in ("VCN", "VCP") or re.match(r"^(아니|아닌|아니라|아닙니다|이라는|이라고)", 뒤맨):
        return None
    # 복합명사·명사구 사이 — `경고 | 신호로`, `손절 | 폭이`, `볼린저 | 밴드`, `적용 | 가격은`.
    # 태그를 못 찾은 말(전문어)은 **어미로 끝나지 않을 때만** 체언으로 본다 — 그냥 체언으로 몰면
    # `닿아 | 매수했음에도`(앞은 용언꼴)까지 막히고, 그냥 빼면 복합명사가 갈린다. 둘 다 겪었다.
    체언 = ("NNG", "NNP", "SL", "SN", "NR", "XSN", "XR")
    앞체언 = 앞태 in 체언 or (앞태 is None and not re.search(r"[아어여고며면니지게기야요다서워해]$", 앞맨))
    if 앞체언 and (뒤첫 in 체언 or 뒤첫 is None): return None

    # ② 등급 — 낮을수록 좋은 자리
    # 2급 — **절이 끝난 자리**. 종결어미와 **대등·종속 연결어미**만이다.
    # `-게`(부사형)와 `-아/어/여`(보조적)는 절을 닫지 않는다 — 뒤의 용언·목적어와 한 덩어리로 읽힌다.
    # 이정찬은 `타이트하게 | 손절선을`·`지나치게 | 커진다면`·`추세에 맞추어 | 진입을` 을 안 끊었다 (2026-10-02).
    if 앞태 == "EF": return 2
    if 앞태 in ("EC", "EC_대등") and 절닫는어미.search(앞맨): return 2
    if 앞태 in ("ETM", "JX", "JKB", "JKS", "JKO", "JKC", "EC", "EC_대등", "EC_보조"):
        return 3                                         # 3급 · 조각이 아주 길 때만
    return 4                                             # 그 밖 — 되도록 쓰지 않는다


def 조각내기(문장, 최대=None, 최소=None, 이상=None):
    """문장 → 구·절 단위 자막 조각들."""
    최대 = 최대기본 if 최대 is None else 최대
    어절들 = [w for w in 문장.split() if w]
    if not 어절들: return []
    n = len(어절들)
    벌 = {i: 경계벌점(어절들, i) for i in range(1, n)}

    def 길이(a, b): return len(맨("".join(어절들[a:b])))

    def 가르기(등급까지):
        """그 등급까지의 자리에서만 끊는다."""
        자리 = [0] + [i for i in range(1, n) if 벌.get(i) is not None and 벌[i] <= 등급까지] + [n]
        return [(자리[k], 자리[k + 1]) for k in range(len(자리) - 1)]

    # 1급·2급(구두점·절 끝)만으로 가른다. 글자 수는 보지 않는다.
    조각 = 가르기(2)
    # **마지막 수단** — 그래도 아주 긴 조각이 남으면 그 조각 안에서만 3급 자리를 쓴다.
    낼것 = []
    for a, b in 조각:
        if 길이(a, b) <= 아주길다:
            낼것.append((a, b)); continue
        # 3급 가운데 **관형절(ETM) 뒤는 쓰지 않는다** — `매달 새로운 | 최신 보조지표와` 처럼
        # 꾸밈말과 꾸밈받는 말이 갈린다 (이정찬 대조 2026-10-02). 조사 뒤만 쓴다.
        안자리 = [i for i in range(a + 1, b)
                 if 벌.get(i) is not None and 벌[i] <= 3
                 and 끝태그(어절들[i - 1]) != "ETM"
                 and not (끝태그(어절들[i - 1]) == "JKB"
                          and 첫태그(어절들[i]) in ("VV", "VA", "VX"))]
        if not 안자리:
            안자리 = [i for i in range(a + 1, b) if 벌.get(i) is not None]
        if not 안자리:
            낼것.append((a, b)); continue
        # 긴 조각을 거의 반으로 가르는 자리를 고른다 (글자 수가 아니라 '너무 길다' 를 푸는 용도)
        목표 = (a + b) / 2.0
        쪼갤 = min(안자리, key=lambda i: abs(i - 목표))
        낼것 += [(a, 쪼갤), (쪼갤, b)]
    return [" ".join(어절들[a:b]) for a, b in 낼것]


