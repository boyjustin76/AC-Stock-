"""한국어 자막 큐를 **구·절 단위**로 가른다. 글자 수가 아니라 형태소 태그가 기준이다.

왜 따로 만들었나 (2026-10-01, 마01 이정찬 지적 "자막이 기준이 없이 나뉘어져있어")
  `srt_rules.split_cue` 는 길이를 맞추는 쪽이라 말이 안 되는 자리에서 끊긴다. 실제로 나온 것:
    `… 수치로 알려` / `주는 하나의 기준선일 뿐입니다`   ← 본용언과 보조용언을 갈랐다
    `… 하나가 아닌 두` / `개를 겹쳐 사용하는`           ← 수관형사와 의존명사를 갈랐다
    `… 사용하는 '더블 볼린저` / `밴드' 매매법을 통해,`    ← 따옴표 안을 갈랐다
    `… 있다는 객관적인` / `경고 신호로 받아들여야 합니다` ← 관형형과 꾸밈받는 말을 갈랐다
    `… 추세를 형성하기` / `시작할 때는 문제가 달라집니다` ← 명사형과 서술어를 갈랐다
  `split_cue` 는 숏폼 14자 규칙을 사람 수정본(S015·S016)으로 맞춘 것이라 손대지 않는다.
  이 모듈은 **롱폼 낭독 자막** 전용이다.

판정은 짐작이 아니라 **모두의 말뭉치 형태 분석(MP)** 에서 뽑은 태그 모델로 한다.
  글자만 보면 `설정은`(명사+보조사 JX)과 `깊은`(용언+관형형 ETM)을 가를 수 없다. 말뭉치에는 답이 있다.
  모델은 `tools/cutedit/data/ko_tags.json.gz` (어절 33.6만개에서 뽑은 끝꼴·앞꼴 태그 · 0.4MB).
  만드는 법은 `ko_tags_build.py`. 모델이 없으면 글자꼴 규칙으로 물러난다(정확도만 떨어진다).

기준
  ① **못 끊는 자리** — 관형형(ETM)·관형격(JKG '의')·관형사(MM) 뒤 · 명사형(ETN) 뒤 ·
     의존명사(NNB)만으로 끝난 뒤 · 뒤가 보조용언(VX)이나 의존명사(NNB)일 때 · 따옴표·괄호 안
  ② **좋은 자리** — 마침표·쉼표(0) > 종결어미 EF(1) > 대등 연결어미 -고/며/면/지만…(1)
     > 보조사 JX·부사격 JKB(3) > 격조사 JKS/JKO(4) > 보조적 연결어미 -아/어/게/지(5) > 그 밖(7)
  ③ 길이는 **기준이 아니라 한계**다. 5~18자를 벗어나면 벌점만 준다. 짧은 쪽이 낫다.
  동적 계획법으로 ②+③ 합이 가장 작은 가름을 고른다.
"""
import gzip
import io
import json
import os
import re

# 이정찬: "좀 짧게 잘라도 되니까" — 이상 길이를 11자로 두고 15자를 넘으면 벌점을 더 준다
최대기본, 최소기본, 이상기본 = 18, 5, 11
길어짐기준 = 15
_모델 = None


def 모델():
    global _모델
    if _모델 is None:
        길 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "ko_tags.json.gz")
        try:
            with gzip.open(길, "rt", encoding="utf-8") as f:
                _모델 = json.load(f)
        except Exception:
            _모델 = {"어절": {}, "끝꼴": {}, "앞꼴": {}, "보조용언": [], "의존명사": []}
        _모델.setdefault("어절", {})
    return _모델


# 길이를 셀 때 공백과 **가느다란 기호**(+ → ·)는 안 센다 — 화면에서 글자 폭을 거의 안 먹는다.
# 이걸 세면 `밴드 확장 + 강한 장대봉 동반 → 추세 추종 매매` 가 한계를 넘어 `추종 매매` 4자로 쪼개진다.
맨 = lambda s: re.sub(r"[\s+→·]", "", s)
_군더더기 = re.compile(r"""[\s'"‘’“”.,!?()\[\]/·…~\-+:;]""")
알만 = lambda s: _군더더기.sub("", s)

# 말뭉치에 없는 꼴을 만났을 때 쓰는 물러섬 규칙 (글자꼴만 본다)
_물러_끝 = [
    (re.compile(r"(습니다|입니다|니다|세요|십시오|어요|아요|예요|죠|까요|나요)$"), "EF"),
    (re.compile(r"(면서|지만|는데|니까|거나|더라도|도록|므로|다가|라면|다면|고자|려고|으며|으면|고|며|면)$"), "EC_대등"),
    (re.compile(r"(아서|어서|여서|아야|어야|여야|아|어|여|게|지|고서)$"), "EC_보조"),
    (re.compile(r"(기|음|ㅁ)$"), "ETN"),
    (re.compile(r"(적인|스러운|같은|다운|로운|하는|되는|있는|없는|했던|하던|되던|던|할|될)$"), "ETM"),
    (re.compile(r"의$"), "JKG"),
    (re.compile(r"(은|는|도|만|까지|부터|마다|조차|밖에|이나|라도)$"), "JX"),
    (re.compile(r"(에서|에게|한테|으로|로|와|과|에|보다|처럼|같이)$"), "JKB"),
    (re.compile(r"(을|를|이|가)$"), "JKO"),
]
_한음절관형 = {"두", "한", "세", "네", "다섯", "여섯", "몇", "여러", "각", "이", "그", "저",
               "매", "온", "전", "새", "첫", "옛", "약", "총", "뭐", "무슨", "어떤", "모든"}


def 끝태그(어절):
    """어절의 **끝 형태소 태그**. ① 말뭉치 어절 사전 ② 끝꼴(2글자 이상) ③ 글자꼴 규칙."""
    글 = 알만(어절)
    if not 글: return None
    낱 = 모델()["어절"].get(글)
    if 낱: return 낱[1]
    표 = 모델()["끝꼴"]
    for k in range(min(5, len(글)), 1, -1):              # 1글자 꼴은 안 쓴다 — 너무 모호하다
        값 = 표.get(글[-k:])
        if 값 and 값[1] >= 0.75 and 값[2] >= 3:
            return 값[0]
    # 글자꼴 물러섬 — **어간이 남아 있을 때만** 쓴다. `경고` 를 `고`(EC)로 읽던 버그를 막는다
    for 재, 태 in _물러_끝:
        m = 재.search(글)
        if m and len(글) - (m.end() - m.start()) >= 2: return 태
    return None


def 첫태그(어절):
    글 = 알만(어절)
    if not 글: return None
    낱 = 모델()["어절"].get(글)
    if 낱: return 낱[0]
    표 = 모델()["앞꼴"]
    for k in range(min(4, len(글)), 1, -1):
        값 = 표.get(글[:k])
        if 값 and 값[1] >= 0.75 and 값[2] >= 3:
            return 값[0]
    return None


# 어간 뒤에 붙는 어미 꼴 — 보조용언을 알아볼 때 쓴다
_어미꼬리 = re.compile(r"^(는|은|ㄴ|던|을|ㄹ|지|고|서|면|며|니|나|자|게|기|음|도록|려고"
                       r"|았|었|겠|아|어|여|야|요|다|까|네|죠"
                       r"|습니다|ㅂ니다|니다|세요|십시오|어요|아요|는다|ㄴ다|는데|지만"
                       r"|으며|으면|으니|으나|으므로|으면서|으려고|으시|었으|겠으"
                       r"|아서|어서|여서|아야|어야|여야|기는|지는)+$")


def _보조용언인가(어절):
    """`주는`·`않고`·`합니다`·`있다는` 처럼 앞말에 붙어 쓰이는 보조용언인가.

    어간만 보고 앞가지로 맞추면 안 된다 — 보조용언 목록에 `가` 가 있어서 **`가격이`** 를
    보조용언으로 읽었고, 그 바람에 쉼표 뒤(`불구하고, | 가격이`)를 못 끊었다 (2026-10-01 실측).
    어간 뒤가 **어미** 일 때만 보조용언으로 본다.
    """
    글 = 알만(어절)
    if 첫태그(어절) == "VX": return True
    if 글 in 모델()["보조용언"]: return True
    for w in 모델()["보조용언"]:
        if 글.startswith(w) and len(글) > len(w) and _어미꼬리.match(글[len(w):]):
            return True
    return False


_조사꼬리 = re.compile(
    r"^(이|가|은|는|을|를|에|의|도|만|과|와|로|으로|에서|에게|부터|까지|보다|처럼|이나|나"
    r"|이다|이라|이며|이고|입니다|이면|이지만|이므로|라도|조차|마저|밖에|마다|뿐|씩|째)?$")


def _의존명사인가(어절):
    """의존명사(+조사) 꼴인가. `개를`·`것은`·`수`·`때는` ○ / `적용`·`개발`·`일정한` ×

    느슨하게 보면 안 된다 — `적` 이 의존명사라고 `적용` 을 의존명사로 읽어서
    `… 편차 4, 적용` / `가격은 …` 처럼 복합명사를 가르는 쪽으로 몰렸다 (2026-10-01 실측).
    """
    글 = 알만(어절)
    if 첫태그(어절) == "NNB" and _조사꼬리.match(글[1:] if len(글) > 1 else ""): return True
    for w in 모델()["의존명사"]:
        if 글 == w: return True
        if 글.startswith(w) and _조사꼬리.match(글[len(w):]) and 글[len(w):]: return True
    return False


# 앞의 체언 없이는 못 서는 용언들 — `~에도 불구하고`, `~에 비해`, `~을 통해`, `~에 대해`
의존용언 = {"불구하고", "불구하여", "비해", "비하여", "대해", "대하여", "대한", "위해", "위하여", "위한",
            "통해", "통하여", "통한", "관해", "관하여", "관한", "의해", "의하여", "의한",
            "따라", "따라서는", "달리", "있어", "있어서", "한하여", "제외하고", "비롯한", "비롯해", "대비", "기준으로", "한해"}


_보조적어미끝 = re.compile(r"(아|어|여|려|워|해|야|게|지|고|기)$")


def 경계벌점(어절들, i):
    """어절 i-1 과 i 사이에서 끊는 값. None 이면 끊을 수 없다."""
    앞, 뒤 = 어절들[i - 1], 어절들[i]
    앞맨 = 알만(앞)

    # ① 따옴표·괄호 안
    글 = " ".join(어절들[:i])
    for 열, 닫 in (("‘", "’"), ("“", "”"), ("(", ")"), ("[", "]")):
        if 글.count(열) > 글.count(닫): return None
    for 짝 in ("'", '"'):
        if 글.count(짝) % 2: return None

    앞태, 뒤태 = 끝태그(앞), 끝태그(뒤)
    if 앞맨 in _한음절관형: return None                  # `두 | 개를`, `이 | 검정색`
    # 관형사 태그는 MM·MMD(지시)·MMA(성상)·MMN(수) 로 갈린다 — 앞가지로 한꺼번에 막는다
    if 앞태 and (앞태.startswith("MM") or 앞태 in ("ETM", "JKG", "ETN", "NNB", "XPN", "MAJ")):
        return None
    if _의존명사인가(뒤): return None                    # `두 | 개를`, `확대될 | 수 있다는`
    if 알만(뒤) in 의존용언: return None                 # `매수했음에도 | 불구하고`, `밴드에 | 비해`
    if _보조용언인가(뒤) and (앞태 in ("EC", "EC_보조", "ETN") or _보조적어미끝.search(앞맨)):
        return None                                      # `알려 | 주는`, `머물지 | 않고`, `받아들여야 | 합니다`

    # ② 좋은 자리
    if re.search(r"[.?!…]$", 앞.strip()): return 0
    if re.search(r"[,;:]$", 앞.strip()): return 0
    if 앞태 == "EF": return 1
    if 앞태 == "EC":
        return 1 if re.search(r"(면서|지만|는데|니까|거나|더라도|도록|므로|다가|고|며|면)$", 앞맨) else 5
    if 앞태 == "EC_대등": return 1
    if 앞태 == "EC_보조": return 5
    뒤첫 = 첫태그(뒤)
    if 앞태 in ("JX", "JKB", "JC"):
        # 부사어와 그 서술어는 단단히 묶인다 — `지속적으로 | 움직이는`, `밴드에 | 닿았다는`
        return 8 if (앞태 == "JKB" and 뒤첫 in ("VV", "VA", "VX", "VCP", "VCN")) else 3
    # 주어와 서술어도 떼면 주어가 떠 보인다 — `제가 | 운영하는`
    if 앞태 == "JKS":
        return 8 if 뒤첫 in ("VV", "VA", "VX", "VCP", "VCN") else 4
    if 앞태 in ("JKO", "JKC"): return 6                  # 목적어는 서술어와 더 단단히 묶인다
    # 조사가 없는 체언 뒤 — `경고 | 신호로` 처럼 복합명사·명사구를 가를 위험이 크다.
    # 태그를 못 찾은 것(None)도 체언으로 본다 — 말뭉치에 없는 전문어(볼린저·휩소)가 대부분이다
    # 태그를 못 찾은 말(전문어·고유어)은 **어미로 끝나지 않을 때만** 체언으로 본다.
    # 그냥 체언으로 몰면 `닿아 | 매수했음에도`(앞은 용언꼴) 까지 막혀 엉뚱한 자리를 고르고,
    # 그냥 빼면 `손절 | 폭이`·`볼린저 | 밴드` 같은 복합명사가 갈린다. 둘 다 실측으로 겪었다.
    체언 = ("NNG", "NNP", "SL", "SN", "NR", "XSN", "XR")
    앞체언 = 앞태 in 체언 or (앞태 is None and not re.search(r"[아어여고며면니지게기야요다서워해]$", 앞맨))
    뒤체언 = 뒤첫 in 체언 or 뒤첫 is None
    if 앞체언 and 뒤체언:
        return 12
    return 7


def 조각내기(문장, 최대=최대기본, 최소=최소기본, 이상=이상기본):
    """문장 → 구·절 단위 자막 조각들."""
    어절들 = [w for w in 문장.split() if w]
    if not 어절들: return []
    n = len(어절들)
    벌 = {i: 경계벌점(어절들, i) for i in range(1, n)}

    def 길이(a, b): return len(맨("".join(어절들[a:b])))

    def 길이벌(L):
        if L > 최대: return 1000 + (L - 최대) * 50       # 한계 — 달리 길이 없을 때만
        if L < 최소: return (최소 - L) * 4
        값 = abs(L - 이상) * 0.3                         # 약하게만 당긴다
        if L > 길어짐기준: 값 += (L - 길어짐기준) * 1.5   # 긴 큐보다 짧은 큐가 낫다
        return 값

    끝까지 = [None] * (n + 1)
    끝까지[n] = (0.0, n)
    for a in range(n - 1, -1, -1):
        최선 = None
        for b in range(a + 1, n + 1):
            if b < n and 벌.get(b) is None: continue
            L = 길이(a, b)
            if L > 최대 and b > a + 1: break
            값 = 길이벌(L) + (벌.get(b, 0) if b < n else 0) + 끝까지[b][0]
            if 최선 is None or 값 < 최선[0]: 최선 = (값, b)
        끝까지[a] = 최선 or (1e9, n)
    조각, a = [], 0
    while a < n:
        b = 끝까지[a][1]
        조각.append(" ".join(어절들[a:b]))
        a = b
    return 조각


